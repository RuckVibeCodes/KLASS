/**
 * Gemini Client — Google AI integration for image generation
 * 
 * Used for:
 * - Generating program thumbnails
 * - Generating course imagery
 * 
 * Requires GEMINI_API_KEY environment variable.
 */

import { GoogleGenerativeAI } from "@google/generative-ai";
import { createAdminClient } from "@/lib/supabase/server";

let _genAI: GoogleGenerativeAI | null = null;

function getClient(): GoogleGenerativeAI {
  if (!_genAI) {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      throw new Error(
        "GEMINI_API_KEY is not set. Add it to your environment variables."
      );
    }
    _genAI = new GoogleGenerativeAI(apiKey);
  }
  return _genAI;
}

/**
 * Check if Gemini AI is available
 */
export function isGeminiAvailable(): boolean {
  return !!process.env.GEMINI_API_KEY;
}

/**
 * Generate a program thumbnail image
 */
export async function generateProgramThumbnail(
  title: string,
  description: string,
  primaryColor: string = "#6366f1",
  accentColor: string = "#8b5cf6"
): Promise<Buffer> {
  const genAI = getClient();
  const model = genAI.getGenerativeModel({ 
    model: "gemini-2.0-flash-exp-image-generation" 
  });

  const prompt = `Create a modern, professional course thumbnail banner.

Title context: "${title}"
Description context: "${description}"

Style requirements:
- Clean gradient background using colors ${primaryColor} to ${accentColor}
- Modern, flat design with abstract icons related to the topic
- Professional course banner aesthetic
- 16:9 aspect ratio (wide banner format)
- NO TEXT whatsoever - icons and shapes only
- Suitable for an online learning platform

The image should feel premium, professional, and visually represent the course topic through abstract iconography.`;

  const result = await model.generateContent({
    contents: [{ role: "user", parts: [{ text: prompt }] }],
    generationConfig: {
      responseModalities: ["image", "text"],
    } as Record<string, unknown>,
  });

  const response = result.response;
  const parts = response.candidates?.[0]?.content?.parts;

  if (!parts) {
    throw new Error("No response from Gemini");
  }

  for (const part of parts) {
    if ("inlineData" in part && part.inlineData) {
      const imageData = part.inlineData.data;
      return Buffer.from(imageData, "base64");
    }
  }

  throw new Error("No image generated by Gemini");
}

/**
 * Upload image to Supabase storage and return public URL
 */
export async function uploadProgramImage(
  communityId: string,
  programId: string,
  imageBuffer: Buffer
): Promise<string> {
  const supabase = await createAdminClient();
  const timestamp = Date.now();
  const path = `${communityId}/${timestamp}-program-${programId}.png`;

  const { error } = await supabase.storage
    .from("community-assets")
    .upload(path, imageBuffer, {
      contentType: "image/png",
      upsert: true,
    });

  if (error) {
    throw new Error(`Failed to upload image: ${error.message}`);
  }

  const { data: { publicUrl } } = supabase.storage
    .from("community-assets")
    .getPublicUrl(path);

  return publicUrl;
}
